using Unity.Mathematics;
using UnityEngine;

public class HabilityBehaviour : StateMachineBehaviour
{
    [SerializeField] private GameObject hability;
    private RoyalGuard boss;
    private Transform player;
    // OnStateEnter is called when a transition starts and the state machine starts to evaluate this state
    override public void OnStateEnter(Animator animator, AnimatorStateInfo stateInfo, int layerIndex)
    {
        boss = animator.GetComponent<RoyalGuard>();
        player = boss.player;

        Vector2 spawnPosition = new Vector2(player.position.x, player.position.y);

        Instantiate(hability, spawnPosition, quaternion.identity);
    }

    // OnStateUpdate is called on each Update frame between OnStateEnter and OnStateExit callbacks
    override public void OnStateUpdate(Animator animator, AnimatorStateInfo stateInfo, int layerIndex)
    {
        if (boss != null && boss.player != null)
        boss.lookingPlayer();
    }

